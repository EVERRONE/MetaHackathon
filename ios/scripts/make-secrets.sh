#!/bin/zsh
# Writes ios/Config/Secrets.xcconfig (gitignored) from the repo-root .dev.vars.
# Usage: ios/scripts/make-secrets.sh [TEAM_ID]
set -euo pipefail
ROOT=${0:A:h:h:h}
TOKEN=$(awk -F= '/^PIP_APP_TOKEN=/{print $2}' "$ROOT/.dev.vars")
[[ -n "$TOKEN" ]] || { echo "PIP_APP_TOKEN missing in .dev.vars" >&2; exit 1; }
OUT="$ROOT/ios/Config/Secrets.xcconfig"
{
  echo "// Generated by make-secrets.sh. Never commit."
  echo "PIP_APP_TOKEN = $TOKEN"
  [[ -n "${1:-}" ]] && echo "DEVELOPMENT_TEAM = $1"
} > "$OUT"
chmod 600 "$OUT"
echo "wrote $OUT"
